    #[test]
    fn legacy_migration_basic() {
        let mut r = rng();
        // Produce a fake PMV1 file: same layout as PMV2 but magic PMV1 +
        // encryption by PBKDF2-derived key from password+salt.
        let password = b"legacypw";
        let salt: Vec<u8> = (0..SALT_LEN).map(|i| i as u8).collect();
        let nonce: Vec<u8> = (0..NONCE_LEN).map(|i| i as u8).collect();
        let legacy_key = legacy_derive_key(password, &salt);

        let plain = serde_json::to_vec(&serde_json::json!({
            "__version": 1,
            "secrets": {"API_KEY": "abc"},
            "envfiles": {},
        }))
        .unwrap();

        // Build header with PMV1
        let header = build_header(MAGIC_V1, &salt);
        let cipher = Aes256Gcm::new(Key::<Aes256Gcm>::from_slice(&legacy_key));
        let ct_tag = cipher
            .encrypt(
                Nonce::from_slice(&nonce),
                Payload {
                    msg: &plain,
                    aad: &header,
                },
            )
            .unwrap();
        let (ct, tag) = ct_tag.split_at(ct_tag.len() - TAG_LEN);
        let mut legacy_file = Vec::new();
        legacy_file.extend_from_slice(&header);
        legacy_file.extend_from_slice(&nonce);
        legacy_file.extend_from_slice(ct);
        legacy_file.extend_from_slice(tag);

        let result = migrate_legacy_deterministic(&legacy_file, password, &mut r).unwrap();
        assert_eq!(result.device_key.len(), KEY_LEN);
        assert_eq!(result.secrets["API_KEY"], serde_json::json!("abc"));
        // New file should decrypt with the new device-key
        let decrypted = decrypt_with_key(&result.new_file, &result.device_key).unwrap();
        let v: Value = serde_json::from_slice(&decrypted).unwrap();
        assert_eq!(v["secrets"]["API_KEY"], serde_json::json!("abc"));
        assert_eq!(v["__version"], serde_json::json!(2));
    }

