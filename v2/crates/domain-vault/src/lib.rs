//! Pure-domain port of `plugin/scripts/vault.cjs`.
//!
//! Scope covered by this crate:
//! - binary file layout (parse + build header)
//! - AES-256-GCM encrypt/decrypt with header as AAD
//! - scrypt (current) + PBKDF2-SHA512 (legacy) password hashing
//! - auth-block construction and verification
//! - store JSON normalization
//! - export/import bundle cryptography
//! - input validation regexes (secret name / envfile name)
//! - legacy migration crypto (key derivation from password)
//!
//! NOT in scope (belongs to a future adapter):
//! - filesystem I/O (`writeFileSafe`, `loadStore`, etc.)
//! - device-key persistence
//! - in-process caches (`_cachedDeviceKey`, `_uiSession`)
//! - UI session / TTL tracking
//! - gitignore management
//!
//! Random salts / nonces are generated by the caller when needed, so
//! the crypto functions are fully deterministic given their inputs —
//! required for cross-language parity tests.

