// ─── Constants ──────────────────────────────────────────────────────

pub const MAGIC_V1: &[u8; 4] = b"PMV1";
pub const MAGIC_V2: &[u8; 4] = b"PMV2";
pub const SALT_LEN: usize = 32;
pub const NONCE_LEN: usize = 12;
pub const TAG_LEN: usize = 16;
pub const KEY_LEN: usize = 32;
pub const PW_SALT_LEN: usize = 16;
pub const PW_HASH_LEN: usize = 64;
pub const KDF_ITERS: u32 = 600_000;
pub const DEFAULT_TTL_MS: u64 = 30 * 60 * 1000;
pub const DEVICE_KEY_FILE: &str = ".vault-devicekey";

// scrypt OWASP 2023: N=2^15, r=8, p=1
pub const SCRYPT_LOG_N: u8 = 15;
pub const SCRYPT_R: u32 = 8;
pub const SCRYPT_P: u32 = 1;

pub const EXPORT_MAGIC: &[u8; 7] = b"PMVEXP1";

pub const GITIGNORE_MARKER: &str = "# project-mem vault — nunca commitar";
pub const GITIGNORE_ENTRIES: &[&str] =
    &["vault.enc", ".vault-devicekey", ".vault-unlock-state.json"];

